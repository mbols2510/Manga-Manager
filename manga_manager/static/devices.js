// Settings > Devices: create, list and revoke Android companion tokens.
// The pairing code is only ever held in the DOM until dismissed: no storage, no logging.
(() => {
  const $ = (s) => document.querySelector(s);
  const esc = (t) => String(t ?? '').replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[c]));
  const fmt = (iso) => iso ? new Date(iso).toLocaleString() : 'never';

  function say(text, kind) {
    const el = $('#dev-status');
    el.textContent = text || '';
    el.className = 'dev-msg' + (kind ? ' ' + kind : '');
  }

  function authOff(message) {
    $('#dev-off').textContent = message;
    $('#dev-off').hidden = false;
    $('#dev-form').hidden = true;
    $('#dev-list').textContent = '';
  }

  async function call(path, opts) {
    const r = await fetch(path, opts);
    let body = null;
    try { body = await r.json(); } catch (e) { /* 204 or non-JSON */ }
    return {status: r.status, body};
  }

  function hidePairing() {
    $('#dev-code').value = '';
    $('#dev-qr').innerHTML = '';
    $('#dev-pair').hidden = true;
  }

  function render(devices) {
    const list = $('#dev-list');
    list.textContent = '';
    if (!devices.length) {
      const p = document.createElement('p');
      p.className = 'empty';
      p.textContent = 'No devices yet.';
      list.append(p);
      return;
    }
    devices.forEach(d => {
      const revoked = !!d.revoked_at;
      const row = document.createElement('div');
      row.className = 'dev-row' + (revoked ? ' revoked' : '');
      const cls = revoked ? 'bad' : 'ok', label = revoked ? 'revoked' : 'active';
      row.innerHTML = `<span class="name">${esc(d.name)}</span>` +
        `<span class="pill ${cls}">${label}</span>` +
        `<span class="meta">created ${esc(fmt(d.created_at))} · last seen ${esc(fmt(d.last_seen))}</span>`;
      if (!revoked) {
        const b = document.createElement('button');
        b.type = 'button';
        b.className = 'btn sm';
        b.textContent = 'Revoke';
        b.setAttribute('aria-label', 'Revoke ' + d.name);
        b.onclick = () => revoke(d);
        row.append(b);
      }
      list.append(row);
    });
  }

  async function load() {
    const {status, body} = await call('api/v1/devices');
    if (status === 409) return authOff(body.error);
    if (status !== 200) { say('Could not load devices.', 'error'); return; }
    render(body);
  }

  async function revoke(d) {
    if (!confirm(`Revoke "${d.name}"? The app on that device will stop working until you pair it again.`)) return;
    const {status, body} = await call('api/v1/devices/' + encodeURIComponent(d.id), {method: 'DELETE'});
    if (status === 204) say(`Revoked ${d.name}.`, 'ok');
    else say((body && body.error) || 'Could not revoke the device.', 'error');
    load();
  }

  $('#dev-form').addEventListener('submit', async (e) => {
    e.preventDefault();
    const name = $('#dev-name').value.trim();
    if (!name) { say('Give the device a name.', 'error'); return; }
    $('#dev-create').disabled = true;
    try {
      const {status, body} = await call('api/v1/devices', {
        method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({name})});
      if (status === 409) return authOff(body.error);
      if (status !== 201) { say((body && body.error) || 'Could not create the device.', 'error'); return; }
      $('#dev-name').value = '';
      $('#dev-code').value = body.pairing;
      // qr_svg is generated by this server from the pairing code (no user text in it).
      $('#dev-qr').innerHTML = body.qr_svg;
      $('#dev-pair').hidden = false;
      say(`Device "${name}" created. Pair it now: the code is not shown again.`, 'ok');
      $('#dev-code').focus();
      $('#dev-code').select();
      load();
    } finally {
      $('#dev-create').disabled = false;
    }
  });

  $('#dev-copy').onclick = async () => {
    const input = $('#dev-code');
    try { await navigator.clipboard.writeText(input.value); say('Pairing code copied.', 'ok'); }
    catch (e) { input.select(); say('Press Ctrl+C to copy the selected code.'); }
  };
  $('#dev-done').onclick = () => { hidePairing(); say(''); };

  load();
})();
